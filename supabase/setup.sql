-- Run in Supabase SQL Editor. Existing customer, vehicle and job rows are retained.
-- This replaces access policies on these three application tables.
begin;

create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  phone text not null,
  created_at timestamptz default now()
);
create table if not exists public.vehicles (
  id bigint generated by default as identity primary key,
  customer_id bigint references public.customers(id) on delete cascade,
  reg_no text not null unique,
  make text,
  model text,
  year integer,
  engine_capacity text,
  created_at timestamptz default now()
);
create table if not exists public.jobs (
  id bigint generated by default as identity primary key,
  vehicle_id bigint references public.vehicles(id) on delete cascade,
  booking_date date not null,
  status text default 'Pending Confirmation',
  diagnosis_notes text default '',
  parts_ordered text default '',
  amount_due numeric(10,2) default 0,
  payment_status text default 'Unpaid',
  updated_at timestamptz default now()
);
create table if not exists public.app_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.jobs alter column status set default 'Pending Confirmation';
alter table public.jobs drop constraint if exists jobs_status_check;
alter table public.jobs add constraint jobs_status_check
  check (status in ('Pending Confirmation', 'Booked', 'In Progress', 'Rescheduled', 'Completed'));
alter table public.jobs drop constraint if exists jobs_payment_status_check;
alter table public.jobs add constraint jobs_payment_status_check
  check (payment_status in ('Unpaid', 'Paid', 'Pay Later'));
alter table public.jobs drop constraint if exists jobs_amount_due_check;
alter table public.jobs add constraint jobs_amount_due_check check (amount_due >= 0);

create unique index if not exists vehicles_normalized_registration_idx
  on public.vehicles (upper(regexp_replace(reg_no, '\s', '', 'g')));
create index if not exists customers_normalized_phone_idx
  on public.customers (regexp_replace(phone, '[^0-9]', '', 'g'));
create index if not exists vehicles_customer_idx on public.vehicles(customer_id);
create index if not exists jobs_vehicle_idx on public.jobs(vehicle_id);
create index if not exists jobs_booking_date_idx on public.jobs(booking_date, id);
create index if not exists jobs_status_idx on public.jobs(status);

alter table public.customers enable row level security;
alter table public.vehicles enable row level security;
alter table public.jobs enable row level security;
alter table public.app_admins enable row level security;

create or replace function public.is_workshop_admin()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.app_admins where user_id = auth.uid());
$$;
revoke all on function public.is_workshop_admin() from public, anon;
grant execute on function public.is_workshop_admin() to authenticated;

-- Remove older permissive policies: PostgreSQL combines permissive policies with OR.
do $$
declare policy_row record;
begin
  for policy_row in
    select schemaname, tablename, policyname from pg_policies
    where schemaname = 'public' and tablename in ('customers', 'vehicles', 'jobs', 'app_admins')
  loop
    execute format('drop policy %I on %I.%I', policy_row.policyname, policy_row.schemaname, policy_row.tablename);
  end loop;
end $$;

revoke all on public.customers, public.vehicles, public.jobs, public.app_admins from anon, authenticated;
grant select on public.customers, public.vehicles, public.jobs to authenticated;
grant update (booking_date, status, diagnosis_notes, parts_ordered, amount_due, payment_status)
  on public.jobs to authenticated;

create policy owner_read_customers on public.customers for select to authenticated
  using (public.is_workshop_admin());
create policy owner_read_vehicles on public.vehicles for select to authenticated
  using (public.is_workshop_admin());
create policy owner_read_jobs on public.jobs for select to authenticated
  using (public.is_workshop_admin());
create policy owner_update_jobs on public.jobs for update to authenticated
  using (public.is_workshop_admin()) with check (public.is_workshop_admin());

create or replace function public.touch_job_updated_at()
returns trigger language plpgsql set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists jobs_touch_updated_at on public.jobs;
create trigger jobs_touch_updated_at before update on public.jobs
  for each row execute function public.touch_job_updated_at();

-- A single transactional RPC; the public role never reads customer or job rows.
create or replace function public.request_booking(
  p_first_name text,
  p_last_name text,
  p_phone text,
  p_reg_no text,
  p_make text,
  p_model text,
  p_year integer,
  p_engine_capacity text,
  p_booking_date date,
  p_status text default 'Pending Confirmation'
)
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  normalized_reg text := upper(regexp_replace(trim(p_reg_no), '\s', '', 'g'));
  normalized_phone text := regexp_replace(p_phone, '[^0-9]', '', 'g');
  customer_key bigint;
  vehicle_key bigint;
  existing_phone text;
  owner_access boolean := public.is_workshop_admin();
begin
  if p_first_name is null or length(trim(p_first_name)) not between 1 and 80
    or p_last_name is null or length(trim(p_last_name)) not between 1 and 80
    or p_phone is null or p_phone !~ '^\+?[0-9 ()-]{7,25}$' or length(normalized_phone) < 7
    or normalized_reg is null or normalized_reg !~ '^[A-Z0-9]{2,8}$'
    or p_make is null or length(trim(p_make)) not between 1 and 100
    or p_model is null or length(trim(p_model)) not between 1 and 100
    or p_booking_date is null or p_booking_date < (now() at time zone 'Europe/London')::date
    or (p_year is not null and (p_year < 1886 or p_year > extract(year from now()) + 1))
    or (p_engine_capacity is not null and length(p_engine_capacity) > 50)
  then
    raise exception 'Please check your contact details, vehicle details and preferred date.';
  end if;
  if p_status is null or p_status not in ('Pending Confirmation', 'Booked')
    or (p_status <> 'Pending Confirmation' and not owner_access)
  then
    raise exception 'You do not have permission to create a confirmed booking.';
  end if;

  -- Serialize matching intakes to prevent duplicate customers or vehicle races.
  perform pg_advisory_xact_lock(hashtextextended('phone:' || normalized_phone, 0));
  perform pg_advisory_xact_lock(hashtextextended('reg:' || normalized_reg, 0));

  select v.id, v.customer_id, regexp_replace(c.phone, '[^0-9]', '', 'g')
    into vehicle_key, customer_key, existing_phone
    from public.vehicles v left join public.customers c on c.id = v.customer_id
    where upper(regexp_replace(v.reg_no, '\s', '', 'g')) = normalized_reg
    for update of v;

  if vehicle_key is not null then
    -- Never reassign ownership or reveal stored customer information through public intake.
    if existing_phone is distinct from normalized_phone then
      raise exception 'This request needs a manual review. Please contact the workshop to arrange your booking.';
    end if;
  else
    select id into customer_key from public.customers
      where regexp_replace(phone, '[^0-9]', '', 'g') = normalized_phone
        and lower(trim(first_name)) = lower(trim(p_first_name))
        and lower(trim(last_name)) = lower(trim(p_last_name))
      order by id limit 1;
    if customer_key is null then
      insert into public.customers(first_name, last_name, phone)
        values (trim(p_first_name), trim(p_last_name), trim(p_phone))
        returning id into customer_key;
    end if;
    insert into public.vehicles(customer_id, reg_no, make, model, year, engine_capacity)
      values (customer_key, normalized_reg, trim(p_make), trim(p_model), p_year, p_engine_capacity)
      returning id into vehicle_key;
  end if;

  if exists (select 1 from public.jobs where vehicle_id = vehicle_key
    and booking_date = p_booking_date and status <> 'Completed')
  then
    raise exception 'There is already a request or booking for this vehicle on that date. Please contact the workshop for changes.';
  end if;
  insert into public.jobs(vehicle_id, booking_date, status, payment_status, amount_due)
    values (vehicle_key, p_booking_date, p_status, 'Unpaid', 0);
end;
$$;

revoke all on function public.request_booking(text,text,text,text,text,text,integer,text,date,text) from public;
grant execute on function public.request_booking(text,text,text,text,text,text,integer,text,date,text) to anon, authenticated;
commit;

